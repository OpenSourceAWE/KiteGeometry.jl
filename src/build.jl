# Writes src/_structure.jl, the component types of KiteGeometry, from the awesIO schemas
# src/awesio/structure_schema.yml and system_schema.yml, vendored from the commit
# gen/awesio.toml records.
# Run with `julia --project src/build.jl`.
using YAML, OrderedCollections, TOML

SCHEMA = joinpath(@__DIR__, "awesio", "structure_schema.yml")
SYSTEM_SCHEMA = joinpath(@__DIR__, "awesio", "system_schema.yml")
AWESIO = TOML.parsefile(joinpath(@__DIR__, "..", "gen", "awesio.toml"))
OUTPUT = joinpath(@__DIR__, "_structure.jl")
WIDTH = 92

HEADER = """
# SPDX-FileCopyrightText: 2026 Bart van de Lint
# SPDX-License-Identifier: MIT

# DO NOT EDIT THIS FILE
# This file was generated by src/build.jl from
# $(AWESIO["repository"])@$(AWESIO["commit"])
# Update gen/awesio.toml and the vendored schemas instead
"""

COLUMN_TYPES = Dict(
    "component_name" => "NameRef",
    "optional_name" => "Union{Nothing, NameRef}",
    "name_pair" => "NTuple{2, NameRef}",
    "name_list" => "Vector{NameRef}",
    "face_corners" => "Vector{NameRef}",
    "vec3" => "MVector{3, Float64}",
    "matrix3" => "MMatrix{3, 3, Float64, 9}",
    "quaternion" => "MVector{4, Float64}",
    "length" => "Float64",
    "non_negative" => "Float64",
    "material_name" => "NameRef",
    "joints" => "OrderedDict{String, Any}",
)
JSON_TYPES = Dict("string" => "String", "integer" => "Int", "boolean" => "Bool",
                  "number" => "Float64", "object" => "OrderedDict{String, Any}")

"""The unit of each quantity of a system tether's `structure`, which its schema does not
state."""
TETHER_UNITS = Dict("length" => "m", "diameter" => "m", "max_tether_force" => "N")

"""Julia type name of the rows of `block`: `bodies` gives `Body`, `canopy_faces`
`CanopyFace`."""
function type_name(block)
    singular = endswith(block, "ies") ? block[1:(end - 3)] * "y" :
               endswith(block, "ches") ? block[1:(end - 2)] : block[1:(end - 1)]
    return join(uppercasefirst.(split(singular, "_")))
end

"""`text` re-flowed into lines of at most `WIDTH - indent` characters."""
function wrap(text, indent=0)
    lines = String[]
    line = ""
    for word in split(strip(text))
        if !isempty(line) && length(line) + 1 + length(word) > WIDTH - indent
            push!(lines, line)
            line = ""
        end
        line = isempty(line) ? String(word) : line * " " * word
    end
    isempty(line) || push!(lines, line)
    return join(lines, "\n")
end

"""Docstring of a type: its signature, its description and one bullet per field, with
the field's unit where it is a quantity."""
function docstring(signature, description, fields)
    bullets = String[]
    for (name, type, text, unit) in fields
        quantity = unit != "-" || occursin("Float64", type)
        label = quantity ? "`$name::$type` [$unit]" : "`$name::$type`"
        bullet = isempty(text) ? label : "$label: " * strip(text)
        push!(bullets, "- " * replace(wrap(bullet, 2), "\n" => "\n  "))
    end
    return "\"\"\"\n    $signature\n\n$(wrap(description))\n\n" *
           "$(join(bullets, "\n"))\n\"\"\"\n"
end

"""Definition name a `data` item refers to, from its `\$ref`."""
definition(item) = last(split(item["\$ref"], "/"))

"""Julia type of a `data` item: its JSON type's or a union of its JSON types, its
definition's, or that or `nothing` for a `oneOf` of a definition and null."""
function column_type(item)
    if haskey(item, "type")
        item["type"] isa AbstractString && return JSON_TYPES[item["type"]]
        return "Union{$(join((JSON_TYPES[type] for type in item["type"]), ", "))}"
    end
    haskey(item, "oneOf") || return COLUMN_TYPES[definition(item)]
    options = item["oneOf"]
    references = filter(option -> haskey(option, "\$ref"), options)
    length(options) == 2 && length(references) == 1 && Dict("type" => "null") in options ||
        error("a oneOf column must be one definition or null")
    return "Union{Nothing, $(column_type(only(references)))}"
end

"""`(header, Julia type, description, unit)` of every required column of `block`."""
function columns(block, spec)
    parts = filter(part -> haskey(part, "properties"), spec["allOf"])
    length(parts) == 1 || error("block $block has no single allOf entry with properties")
    table = only(parts)["properties"]
    headers = table["headers"]["items"]
    units = table["units"]["items"]
    items = table["data"]["items"]["items"]
    length(headers) == length(units) == length(items) ||
        error("block $block has headers, units and data of different lengths")
    fields = Tuple{String, String, String, String}[]
    for (header, unit, item) in zip(headers, units, items)
        name = header["const"]
        type = name == "name" ? "Symbol" : column_type(item)
        push!(fields, (name, type, header["description"], unit["const"]))
    end
    return fields
end

"""`type` or `nothing`, as Julia source."""
optional_type(type) = startswith(type, "Union{Nothing, ") ? type : "Union{Nothing, $type}"

"""`(header, Julia type, description, unit)` of every optional column of a block's `spec`,
its type admitting `nothing`."""
function optional_columns(spec)
    return [(name, optional_type(column_type(column["value"])),
             "Optional. " * column["description"], column["unit"])
            for (name, column) in get(spec, "optionalColumns", ())]
end

"""Source of the named tuple of the unit of each optional column of a block's `spec`."""
function optional_units_source(spec)
    entries = ["$name = $(repr(unit))" for (name, _, _, unit) in optional_columns(spec)]
    isempty(entries) && return "(;)"
    length(entries) == 1 && return "($(only(entries)),)"
    return "($(join(entries, ", ")))"
end

"""Source of the component type `name` holding `fields`, and the model of a row."""
function row_source(name, description, fields)
    fields = [fields;
              ("model", "M", "the model the `model` column names, else `NoModel`", "-")]
    body = join(("    $field::$type" for (field, type) in fields), "\n")
    return docstring("$name{M}", description, fields) *
           "mutable struct $name{M <: AbstractModel} <: Component\n$body\nend\n"
end

"""Source of the struct holding one row of `block`."""
function component_source(block, spec)
    description = "A row of the `$block` block. " * get(spec, "description", "")
    return row_source(type_name(block), description,
                      [columns(block, spec); optional_columns(spec)])
end

"""`(field, Julia type, description, unit)` of `spec`'s required `properties`, a `name` a
`Symbol`."""
function required_properties(spec)
    return [let property = spec["properties"][name]
                (name, name == "name" ? "Symbol" : column_type(property),
                 get(property, "description", ""), "-")
            end
            for name in spec["required"]]
end

"""Source of `Material`, from the system schema's definition of a material."""
function material_source(definitions)
    return row_source("Material", "A material of a system document. " *
                                  definitions["material"]["description"],
                      required_properties(definitions["material"]))
end

"""`(field, Julia type, description, unit)` of each field of a tether's `structure`, those
not required admitting `nothing`."""
function tether_structure_fields(tether)
    structure = first(tether["allOf"])["then"]["properties"]["structure"]
    return [let required = name in structure["required"], type = column_type(property)
                (name, required ? type : optional_type(type),
                 get(property, "description", ""), get(TETHER_UNITS, name, "-"))
            end
            for (name, property) in structure["properties"]]
end

"""Source of `SystemTether`, from the system schema's definition of a tether: its own
fields, then those of its `structure`."""
function system_tether_source(definitions)
    tether = definitions["tether"]
    own = filter(field -> first(field) != "structure", required_properties(tether))
    description = "A tether of a system document: the design of the whole component, " *
                  "which the tether of a structure sharing its name discretises."
    return row_source("SystemTether", description, [own; tether_structure_fields(tether)])
end

"""Source of the metadata type `name`, from a schema's `metadata` object."""
function metadata_source(name, description, spec)
    fields = [(field, JSON_TYPES[spec["properties"][field]["type"]],
               get(spec["properties"][field], "description", ""), "-")
              for field in spec["required"]]
    body = join(("    $field::$type" for (field, type) in fields), "\n")
    return docstring(name, description, fields) * "struct $name\n$body\nend\n"
end

"""Source of `SystemDefinition`, one vector per table block and per block of its system, and
of `BLOCKS`, `SYSTEM_BLOCKS`, `UNITS` and `OPTIONAL_UNITS`."""
function system_source(schema, blocks, definitions)
    fields = [("metadata", "Metadata", "the document's metadata", "-"),
              ("system_metadata", "SystemMetadata", "the metadata of its system", "-"),
              ("materials", "Rows{Material}", "the materials of its system", "-"),
              ("system_tethers", "Rows{SystemTether}", "the tethers of its system", "-")]
    for (block, _) in blocks
        push!(fields, (block, "Rows{$(type_name(block))}", "the rows of `$block`", "-"))
    end
    push!(fields, ("extras", "OrderedDict{String, Any}",
                   "blocks the schema does not name, in the order read", "-"),
          ("system_extras", "OrderedDict{String, Any}",
           "what its system holds beside materials and tethers, in the order read", "-"))
    body = join(("    $field::$type" for (field, type) in fields), "\n")
    table = join(("    $block = $(type_name(block)),\n" for (block, _) in blocks))
    tether_fields = tether_structure_fields(definitions["tether"])
    tether_optional = ("$name = $(repr(unit))" for (name, type, _, unit) in tether_fields
                       if startswith(type, "Union{Nothing, "))
    units = join(("    $block = ($(join(repr.(last.(columns(block, spec))), ", "))),\n"
                  for (block, spec) in blocks))
    optional_units = join(("    $block = $(optional_units_source(spec)),\n"
                           for (block, spec) in blocks))
    required = join((":$block" for block in schema["required"]), ", ")
    description = "A structure document and the system it names: their metadata, the " *
                  "system's materials and tethers, the rows of each table block, and " *
                  "what the schemas do not name."
    return docstring("SystemDefinition", description, fields) *
           "struct SystemDefinition\n$body\nend\n\n" *
           "\"\"\"The component type of each table block, in schema order.\"\"\"\n" *
           "const BLOCKS = (\n$table)\n\n" *
           "\"\"\"The component type of each list of the system.\"\"\"\n" *
           "const SYSTEM_BLOCKS = (materials = Material, " *
           "system_tethers = SystemTether)\n\n" *
           "\"\"\"The unit of each required column of each table block, in order.\"\"\"\n" *
           "const UNITS = (\n$units)\n\n" *
           "\"\"\"The unit of each optional column of each block, by name.\"\"\"\n" *
           "const OPTIONAL_UNITS = (\n    materials = (;),\n" *
           "    system_tethers = (\n" *
           "        $(join(tether_optional, ",\n        ")),\n    ),\n" *
           "$optional_units)\n\n" *
           "\"\"\"The blocks a structure document must carry.\"\"\"\n" *
           "const REQUIRED_BLOCKS = ($required)\n"
end

"""Source of `AWESIO_VERSION`, the awesIO version gen/awesio.toml records."""
function version_source()
    return "\"\"\"The awesIO version of the vendored schema.\"\"\"\n" *
           "const AWESIO_VERSION = $(repr(AWESIO["awesIO_version"]))\n"
end

"""The source of `_structure.jl` for the structure `schema` and the `system_schema`."""
function structure_source(schema, system_schema)
    properties = schema["properties"]
    definitions = system_schema["definitions"]
    blocks = [(name, spec) for (name, spec) in properties if name != "metadata"]
    parts = [HEADER, version_source(),
             metadata_source("Metadata", "The `metadata` block of a structure document.",
                             properties["metadata"]),
             metadata_source("SystemMetadata", "The `metadata` block of a system document.",
                             system_schema["properties"]["metadata"]),
             material_source(definitions), system_tether_source(definitions),
             (component_source(block, spec) for (block, spec) in blocks)...,
             system_source(schema, blocks, definitions)]
    return join(parts, "\n")
end

load_schema(path) = YAML.load_file(path; dicttype=OrderedDict{String, Any})
write(OUTPUT, structure_source(load_schema(SCHEMA), load_schema(SYSTEM_SCHEMA)))
